/** Configure pins as
        * Analog
        * Input
        * Output
        * EVENT_OUT
        * EXTI
*/
void MX_GPIO_Init(void)
{

  GPIO_InitTypeDef GPIO_InitStruct = {0};

  /* GPIO Ports Clock Enable */
  __HAL_RCC_GPIOF_CLK_ENABLE();
  __HAL_RCC_GPIOH_CLK_ENABLE();
  __HAL_RCC_GPIOB_CLK_ENABLE();
  __HAL_RCC_GPIOE_CLK_ENABLE();
  __HAL_RCC_GPIOD_CLK_ENABLE();
  __HAL_RCC_GPIOA_CLK_ENABLE();
  __HAL_RCC_GPIOC_CLK_ENABLE();
  __HAL_RCC_GPIOI_CLK_ENABLE();

  /*Configure GPIO pin Output Level */
  HAL_GPIO_WritePin(DRIVER_EN_L_GPIO_Port, DRIVER_EN_L_Pin, GPIO_PIN_RESET);

  /*Configure GPIO pin Output Level */
  HAL_GPIO_WritePin(DRIVER_EN_R_GPIO_Port, DRIVER_EN_R_Pin, GPIO_PIN_RESET);

  /*Configure GPIO pins : TRACK0_Pin TRACK1_Pin TRACK2_Pin TRACK7_Pin
                           TRACK6_Pin TRACK5_Pin TRACK4_Pin TRACK3_Pin */
  GPIO_InitStruct.Pin = TRACK0_Pin|TRACK1_Pin|TRACK2_Pin|TRACK7_Pin
                          |TRACK6_Pin|TRACK5_Pin|TRACK4_Pin|TRACK3_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_INPUT;
  GPIO_InitStruct.Pull = GPIO_PULLUP;
  HAL_GPIO_Init(GPIOF, &GPIO_InitStruct);

  /*Configure GPIO pin : DRIVER_EN_L_Pin */
  GPIO_InitStruct.Pin = DRIVER_EN_L_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_NOPULL;
  GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(DRIVER_EN_L_GPIO_Port, &GPIO_InitStruct);

  /*Configure GPIO pin : DRIVER_EN_R_Pin */
  GPIO_InitStruct.Pin = DRIVER_EN_R_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_NOPULL;
  GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(DRIVER_EN_R_GPIO_Port, &GPIO_InitStruct);

  /*Configure GPIO pins : ENC_L_Pin ENC_R_Pin */
  GPIO_InitStruct.Pin = ENC_L_Pin|ENC_R_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_IT_RISING;
  GPIO_InitStruct.Pull = GPIO_PULLUP;
  HAL_GPIO_Init(GPIOI, &GPIO_InitStruct);

  /* EXTI interrupt init*/
  HAL_NVIC_SetPriority(EXTI9_5_IRQn, 1, 0);
  HAL_NVIC_EnableIRQ(EXTI9_5_IRQn);

}

